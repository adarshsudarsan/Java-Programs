package javapackage;

public class Datatypespgm {

	public static void main(String[] args) {
		
		byte byteNumber=10;
		System.out.println("Byte number :" + byteNumber);

		short shortNumber=5;
		System.out.println("Short number :" +shortNumber);
		
		int intNumber=7;
		System.out.println("Int number : "+intNumber);
		
		long longNumber=123456789L;
		System.out.println("long number :" +longNumber);
		
		float floatNumber=77.77F;
		System.out.println("Float number :" +floatNumber);
		
		double doubleNumber=1000.00;
		System.out.println("Double number :" +doubleNumber);
		
		boolean booleanNumber=30>40;
		System.out.println("Result of boolean value :" +booleanNumber);
		
		char charaterValue='A';
		System.out.println("Grade :" +charaterValue);
		
		char symbol='@';
		System.out.println("symbol :" +symbol);
		
		String stringValue = "Adarsh Sudarsan"; //string "S" should be upper case
		System.out.println("The name is "+stringValue);
	}

}
